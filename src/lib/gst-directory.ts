export type ProductType = 'physical' | 'digital' | 'service';

export type ITCEligibility = 
  | 'full'       // Full Input Tax Credit can be claimed against output tax
  | 'blocked'    // Blocked credit under Section 17(5)
  | 'partial'    // Conditional or proportionate credit
  | 'nil';       // Exempt or zero-rated supply (no ITC available)

export interface GSTCategoryItem {
  code: string;                  // HSN (goods) or SAC (services/digital)
  type: ProductType;
  industry: string;
  category: string;
  subcategory: string;
  name: string;
  ratePercent: number;          // 0, 1.5, 3, 5, 12, 18, 28
  itcEligibility: ITCEligibility;
  itcDescription: string;
  isGSTMandatoryToSell: string;  // Threshold details & e-com requirements
  filingRequirements: string;   // GSTR-1 & 3B schedule
  notes2025: string;
  keywords: string[];
}

export interface GSTPresetOption {
  code: string;
  name: string;
  defaultRate: number;
  industry: string;
  type: ProductType;
}

